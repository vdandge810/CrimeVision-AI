import io, json
from reportlab.lib.pagesizes import letter
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.lib.units import inch

def make_report(evidence_rows, event_rows, case_id="default"):
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=letter, rightMargin=0.6*inch, leftMargin=0.6*inch)
    styles = getSampleStyleSheet()
    story = [
        Paragraph("CrimeVision AI — Evidence Review Report", styles["Title"]),
        Paragraph(f"Case ID: {case_id}", styles["Heading2"]),
        Paragraph("Decision-support output. All automated observations require human verification.", styles["BodyText"]),
        Spacer(1, 12),
        Paragraph("Evidence Register", styles["Heading1"])
    ]
    data = [["ID", "Filename", "Type", "SHA-256", "Status"]]
    for r in evidence_rows:
        data.append([
            str(r["id"]), str(r["filename"])[:28], str(r["media_type"]),
            str(r["sha256"])[:20] + "...", str(r["processing_status"])
        ])
    t = Table(data, repeatRows=1, colWidths=[0.35*inch, 1.65*inch, 0.55*inch, 1.65*inch, 1.1*inch])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (-1,0), colors.HexColor("#243247")),
        ("TEXTCOLOR", (0,0), (-1,0), colors.white),
        ("GRID", (0,0), (-1,-1), 0.4, colors.grey),
        ("VALIGN", (0,0), (-1,-1), "TOP"),
        ("FONTSIZE", (0,0), (-1,-1), 7),
        ("BOTTOMPADDING", (0,0), (-1,-1), 5),
    ]))
    story.extend([t, Spacer(1, 14), Paragraph("Timeline / Recorded Events", styles["Heading1"])])
    if not event_rows:
        story.append(Paragraph("No timeline events recorded.", styles["BodyText"]))
    for ev in event_rows:
        story.append(Paragraph(
            f"<b>{ev['event_time']}</b> — {ev['event_type']}: {ev['description']} "
            f"(source evidence ID: {ev['evidence_id'] or 'N/A'})",
            styles["BodyText"]
        ))
        story.append(Spacer(1, 5))
    story.extend([
        Spacer(1, 16),
        Paragraph("Methodology and Limitations", styles["Heading1"]),
        Paragraph(
            "File hashes are used to help identify whether stored files have changed since hashing; "
            "they do not prove authenticity or acquisition history. Model outputs can contain errors. "
            "This report is generated by an educational MVP and is not a certified forensic report. "
            "Preserve original media and validate all findings independently.",
            styles["BodyText"]
        )
    ])
    doc.build(story)
    buf.seek(0)
    return buf
